

function trafficColor(color){
    if(color == "Red"){
    return "Stop"
    }
    
    else if(color == "Yellow"){
    return "Get Ready"
    }
    
    else if(color == "Green"){
    return "Go"
    }    

}

console.log(trafficColor("Red"))
console.log(trafficColor("Yellow"))
console.log(trafficColor("Green"))

